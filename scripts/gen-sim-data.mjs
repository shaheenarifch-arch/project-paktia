#!/usr/bin/env node
// Generates sim/generated/HavocData.inc from data/units, data/formations and
// data/logistics so the C++ simulation core needs no JSON parser at runtime.
//
// All numbers are written as integer thousandths ("milli") so the sim can turn
// them into Fixed64 values without floating point.
//
//   node scripts/gen-sim-data.mjs          write the file
//   node scripts/gen-sim-data.mjs --check  fail if the file is out of date (CI)
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'sim', 'generated', 'HavocData.inc')
const check = process.argv.includes('--check')

const readDir = (dir, key) =>
  readdirSync(join(root, 'data', dir))
    .filter(f => f.endsWith('.json'))
    .sort()
    .flatMap(f => JSON.parse(readFileSync(join(root, 'data', dir, f), 'utf8'))[key])

const milli = (v, where) => {
  const n = Math.round(Number(v) * 1000)
  if (!Number.isFinite(n)) throw new Error(`Not a number: ${where} = ${v}`)
  return n
}
const str = s => JSON.stringify(String(s))
// Byte order (not locale order) so the C++ side can binary-search with operator<.
const byId = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

const units = readDir('units', 'units').sort((a, b) => byId(a.id, b.id))
const formations = readDir('formations', 'formations').sort((a, b) => byId(a.id, b.id))
const supply = JSON.parse(readFileSync(join(root, 'data', 'logistics', 'supply-classes.json'), 'utf8')).supplyClasses
const unitIds = new Set(units.map(u => u.id))

const perCrew = id => {
  const c = supply.find(s => s.id === id)
  if (!c || !c.perCrewPerDay) throw new Error(`data/logistics: supply class ${id} needs perCrewPerDay`)
  return Object.values(c.perCrewPerDay).reduce((s, v) => s + milli(v, `${id}.perCrewPerDay`), 0)
}

const lines = []
lines.push('// GENERATED by scripts/gen-sim-data.mjs from data/. Do not edit by hand.')
lines.push('// Regenerate with: npm run sim:gen')
lines.push('// Numbers are integer thousandths (milli).')
lines.push('')
lines.push(`HAVOC_PER_CREW_FOOD_MILLI(${perCrew('food_water')})`)
lines.push(`HAVOC_PER_CREW_MEDICAL_MILLI(${perCrew('medical')})`)
lines.push('')
lines.push('// HAVOC_UNIT(id, faction, crew, fuelCapacityMilli, fuelBurnPerDayMilli, ammoCratesMilli, maintenanceHoursMilli)')
for (const u of units) {
  const ammo = Object.values(u.ammo_loadout ?? {}).reduce((s, v) => s + milli(v, `${u.id}.ammo_loadout`), 0)
  lines.push(
    `HAVOC_UNIT(${str(u.id)}, ${str(u.faction)}, ${u.crew | 0}, ${milli(u.fuel_capacity ?? 0, `${u.id}.fuel_capacity`)}, ` +
      `${milli(u.fuel_burn ?? 0, `${u.id}.fuel_burn`)}, ${ammo}, ${milli(u.maintenance_hours ?? 0, `${u.id}.maintenance_hours`)})`
  )
}
lines.push('')
lines.push('// HAVOC_FORMATION_UNIT(formationId, faction, unitId, count)')
for (const f of formations) {
  for (const [unitId, count] of Object.entries(f.units).sort(([a], [b]) => byId(a, b))) {
    if (!unitIds.has(unitId)) throw new Error(`data/formations: ${f.id} references unknown unit ${unitId}`)
    lines.push(`HAVOC_FORMATION_UNIT(${str(f.id)}, ${str(f.faction)}, ${str(unitId)}, ${count | 0})`)
  }
}
const text = lines.join('\n') + '\n'

if (check) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current !== text) {
    console.error('sim/generated/HavocData.inc is out of date. Run: npm run sim:gen')
    process.exit(1)
  }
  console.log('sim data up to date')
} else {
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, text)
  console.log(`wrote ${out}: ${units.length} units, ${formations.length} formations`)
}
