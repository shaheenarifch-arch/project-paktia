// Section: units and formations -> sim/generated/HavocData.inc
// (data/units, data/formations, data/logistics).
import { readJson, readDir, milli, str, byId } from './_util.mjs'

export const output = 'HavocData'

export default function generate() {
  const units = readDir('units', 'units').sort((a, b) => byId(a.id, b.id))
  const formations = readDir('formations', 'formations').sort((a, b) => byId(a.id, b.id))
  const supply = readJson('data', 'logistics', 'supply-classes.json').supplyClasses
  const unitIds = new Set(units.map(u => u.id))

  const perCrew = id => {
    const c = supply.find(s => s.id === id)
    if (!c || !c.perCrewPerDay) throw new Error(`data/logistics: supply class ${id} needs perCrewPerDay`)
    return Object.values(c.perCrewPerDay).reduce((s, v) => s + milli(v, `${id}.perCrewPerDay`), 0)
  }

  const lines = []
  lines.push('// GENERATED by scripts/gen-sim-data.mjs from data/. Do not edit by hand.')
  lines.push('// Regenerate with: npm run sim:gen')
  lines.push('// Numbers are integer thousandths (milli).')
  lines.push('')
  lines.push(`HAVOC_PER_CREW_FOOD_MILLI(${perCrew('food_water')})`)
  lines.push(`HAVOC_PER_CREW_MEDICAL_MILLI(${perCrew('medical')})`)
  lines.push('')
  lines.push('// HAVOC_UNIT(id, faction, crew, fuelCapacityMilli, fuelBurnPerDayMilli, ammoCratesMilli, maintenanceHoursMilli)')
  for (const u of units) {
    const ammo = Object.values(u.ammo_loadout ?? {}).reduce((s, v) => s + milli(v, `${u.id}.ammo_loadout`), 0)
    lines.push(
      `HAVOC_UNIT(${str(u.id)}, ${str(u.faction)}, ${u.crew | 0}, ${milli(u.fuel_capacity ?? 0, `${u.id}.fuel_capacity`)}, ` +
        `${milli(u.fuel_burn ?? 0, `${u.id}.fuel_burn`)}, ${ammo}, ${milli(u.maintenance_hours ?? 0, `${u.id}.maintenance_hours`)})`
    )
  }
  lines.push('')
  lines.push('// HAVOC_FORMATION_UNIT(formationId, faction, unitId, count)')
  for (const f of formations) {
    for (const [unitId, count] of Object.entries(f.units).sort(([a], [b]) => byId(a, b))) {
      if (!unitIds.has(unitId)) throw new Error(`data/formations: ${f.id} references unknown unit ${unitId}`)
      lines.push(`HAVOC_FORMATION_UNIT(${str(f.id)}, ${str(f.faction)}, ${str(unitId)}, ${count | 0})`)
    }
  }
  return lines
}

