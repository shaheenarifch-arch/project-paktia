// Section: world map and strategic routes -> sim/generated/World.inc
// (data/world/*.json, faction ids from data/factions).
import { readdirSync } from 'node:fs'
import { join } from 'node:path'
import { root, readJson, milli, str, byId } from './_util.mjs'

export const output = 'World'

export default function generate() {
  const doc = readJson('data', 'world', 'gardun-gulf.json')
  const factions = readdirSync(join(root, 'data', 'factions'))
    .filter(f => f.endsWith('.json'))
    .map(f => readJson('data', 'factions', f).id)
    .sort(byId)

  const lines = []
  lines.push('// GENERATED by scripts/gen-sim-data.mjs from data/world/. Do not edit by hand.')
  lines.push('// Regenerate with: npm run sim:gen')
  lines.push('// Oil is integer thousandths of a game unit per day (milli). Adjacency ids are resolved by the loader.')
  lines.push('')
  lines.push('// HAVOC_FACTION(id)   (sorted by id; the index is the faction number used in commands and events)')
  for (const f of factions) lines.push(`HAVOC_FACTION(${str(f)})`)
  lines.push('')
  lines.push('// HAVOC_ENEMY(factionA, factionB)   (symmetric)')
  for (const [a, b] of doc.enemies) lines.push(`HAVOC_ENEMY(${str(a)}, ${str(b)})`)
  lines.push('')
  lines.push('// HAVOC_PROVINCE(id, name, owner, terrain, infrastructure, oilMilli, population, isPort, hasAirbase)')
  for (const p of doc.provinces) {
    lines.push(
      `HAVOC_PROVINCE(${str(p.id)}, ${str(p.name)}, ${str(p.owner)}, ${str(p.terrain)}, ${p.infrastructure | 0}, ` +
        `${milli(p.oil, `${p.id}.oil`)}, ${str(p.population)}, ${p.isPort ? 'true' : 'false'}, ${p.hasAirbase ? 'true' : 'false'})`
    )
  }
  lines.push('')
  lines.push('// HAVOC_ZONE(id, name, chokepoint, worldMarket)')
  for (const z of doc.seaZones) {
    lines.push(`HAVOC_ZONE(${str(z.id)}, ${str(z.name)}, ${z.chokepoint ? 'true' : 'false'}, ${z.worldMarket ? 'true' : 'false'})`)
  }
  lines.push('')
  lines.push('// HAVOC_ADJACENT(id, neighbourId)   (one line per direction; ids may be provinces or zones)')
  for (const n of [...doc.provinces, ...doc.seaZones]) {
    for (const o of [...n.adjacent].sort(byId)) lines.push(`HAVOC_ADJACENT(${str(n.id)}, ${str(o)})`)
  }
  lines.push('')
  lines.push('// HAVOC_ROUTE(id, name, mode, owner)  then its HAVOC_ROUTE_LEG(routeId, legId) in order, and HAVOC_ROUTE_EXPORTER(routeId, provinceId)')
  for (const r of doc.routes) {
    lines.push(`HAVOC_ROUTE(${str(r.id)}, ${str(r.name)}, ${str(r.mode)}, ${str(r.owner)})`)
    for (const l of r.legs) lines.push(`HAVOC_ROUTE_LEG(${str(r.id)}, ${str(l)})`)
    for (const e of r.exporters) lines.push(`HAVOC_ROUTE_EXPORTER(${str(r.id)}, ${str(e)})`)
  }
  return lines
}
